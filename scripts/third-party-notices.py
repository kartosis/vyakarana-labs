"""Licence notices for everything compiled into the vidyut WebAssembly (Derivation tool review D6).

MIT and Apache-2.0 ask that their notices travel with copies of the software, and the site serves a copy.
Reads `cargo metadata --format-version 1 --filter-platform wasm32-unknown-unknown` from stdin or a file, walks
the normal (non-dev, non-build) dependency graph from the root crate, and prints, for each crate: name, version,
licence, repository, and the text of the licence files it ships. Standard library only.

Usage: python3 scripts/third-party-notices.py <metadata.json> <root crate name>  > THIRD-PARTY.txt
"""

