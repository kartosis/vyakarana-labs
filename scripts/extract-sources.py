#!/usr/bin/env python3
"""Write the small extract of the ashtadhyayi.com dataset that the content checks need, so they run in CI
(the full dataset is 1.9 GB). ROADMAP P3; data credited on /sources/ (dataset README: free to use with credit).

    python3 scripts/extract-sources.py [path-to-ashtadhyayi-com-data] [out-dir]
    (defaults: $ASHTADHYAYI_DATA or ../ashtadhyayi-com/data; data/sources-extract)

The extract keeps the dataset's file layout, so scripts/check-sutras.py and scripts/check-sources.py run on it
unchanged:
  * sutraani/data.txt          — {"data": [...]}, only the sūtras in data/sutras/*.yaml, only the fields checked
  * sutraani/laghukaumudi.txt  — {id: vṛtti}, only for those sūtras
  * every file a verified quote's checkedAt points to — the Devanagari around each quoted passage (±200 letters),
    already normalised the way check-sources.py compares
Re-run it after adding sūtras or quotes; CI fails until the extract covers them.
"""

import json
import os
import sys
import unicodedata
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SRC = Path(sys.argv[1] if len(sys.argv) > 1 else os.environ.get("ASHTADHYAYI_DATA", ROOT.parent / "ashtadhyayi-com" / "data"))
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "data" / "sources-extract"
PREFIX = "https://github.com/ashtadhyayi-com/data/blob/master/"
FIELDS = ("a", "p", "n", "i", "s", "pc", "skn", "lskn")
WINDOW = 200


def norm(s: str) -> str:
    """Same as check-sources.py: Devanagari letters and signs only."""
    s = unicodedata.normalize("NFC", s)
    return "".join(c for c in s if ("ऀ" <= c <= "ॣ" or "ॱ" <= c <= "ॿ") and c != "ऽ")


def main() -> int:
    ids = {str(r["id"]) for f in (ROOT / "data" / "sutras").glob("*.yaml") for r in yaml.safe_load(f.read_text("utf8"))}
    data = json.loads((SRC / "sutraani" / "data.txt").read_text("utf8"))["data"]
    rows = [{k: x[k] for k in FIELDS if k in x} for x in data if f"{x['a']}.{x['p']}.{x['n']}" in ids]
    lsk = json.loads((SRC / "sutraani" / "laghukaumudi.txt").read_text("utf8"))
    vrttis = {r["i"]: lsk[r["i"]] for r in rows if r.get("i") in lsk}
    (OUT / "sutraani").mkdir(parents=True, exist_ok=True)
    (OUT / "sutraani" / "data.txt").write_text(json.dumps({"data": rows}, ensure_ascii=False, indent=0), "utf8")
    (OUT / "sutraani" / "laghukaumudi.txt").write_text(json.dumps(vrttis, ensure_ascii=False, indent=0), "utf8")

    windows: dict[str, list[str]] = {}
    texts: dict[str, str] = {}
    missing = 0
    for q in yaml.safe_load((ROOT / "data" / "quotes.yaml").read_text("utf8")):
        url = q.get("checkedAt", "")
        if not url.startswith(PREFIX) or not q.get("verified"):
            continue
        rel = url[len(PREFIX) :]
        if rel not in texts:
            texts[rel] = norm((SRC / rel).read_text("utf8"))
        for part in (norm(p) for p in q["deva"].split("…")):
            if not part:
                continue
            at = texts[rel].find(part)
            if at < 0:
                print(f"✗ {q['id']}: not found in {rel}")
                missing += 1
                continue
            windows.setdefault(rel, []).append(texts[rel][max(0, at - WINDOW) : at + len(part) + WINDOW])
    json_files = {"sutraani/data.txt": {"data": rows}, "sutraani/laghukaumudi.txt": vrttis}
    for rel, parts in windows.items():
        (OUT / rel).parent.mkdir(parents=True, exist_ok=True)
        if rel in json_files:  # a quote from a file the sūtra check reads as JSON: keep it JSON, add the passages
            doc = {**json_files[rel], "_quoted": parts}
            (OUT / rel).write_text(json.dumps(doc, ensure_ascii=False, indent=0), "utf8")
        else:
            (OUT / rel).write_text("\n".join(parts) + "\n", "utf8")
    (OUT / "README.md").write_text(
        "# Extract of the ashtadhyayi.com dataset\n\n"
        "From https://github.com/ashtadhyayi-com/data (\"free to use this data in your own projects provided that\n"
        "appropriate credits are mentioned\"), credited on the site's Sources page. Only what the content checks\n"
        "need, so they can run in CI. Generated by `scripts/extract-sources.py`; do not edit by hand.\n",
        "utf8",
    )
    print(f"extract: {len(rows)} sūtras, {len(vrttis)} vṛttis, {sum(map(len, windows.values()))} passages in {len(windows)} files → {OUT}")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
